    assert serve.install(linux, 'owner', tmp_path, False, False, True) == 0
    stage, = set(state.glob('install-*')) - before
    script = (stage / 'install.sh').read_text()
    # Each installed unit must still be the content the owner reviewed when root runs the install.
    assert all(f"  {path}' | sha256sum -c" in script for path, _ in systemd.documents(linux.resolve(), 'owner', tmp_path).values())


