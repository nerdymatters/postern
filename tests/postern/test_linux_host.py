# Generated by Claude Code (ship test coverage audit, pass 1; widened in review to the staged files).
# Value: protects=the printed root command installs only what the owner reviewed, and stops before any install
# or systemctl when a target, a staged unit or install.sh changed after review; fails_when=a guard cannot stop
# set -e (an AND list), the guards move after install, or root reads the owner-writable stage unchecked;
# why_new=other tests only read the script text and run sh -n; seam=none; no_claim=root ownership or real
# systemctl (fake install and systemctl on PATH; real /bin/sh, mktemp, timeout, head and GNU sha256sum)
@pytest.mark.skipif(not GNU_SHA256SUM, reason='the root step uses GNU sha256sum -c, as Debian and Ubuntu have')
@pytest.mark.parametrize('change', ['none', 'force unchanged', 'unit appeared', 'unit edited', 'drop-in appeared', 'staged unit edited', 'install.sh edited',
                                    'install.sh is /dev/zero', 'staged unit is /dev/zero'])
def test_root_install_runs_only_what_the_owner_reviewed(linux, tmp_path, change, capsys):
    api = systemd.UNIT_DIR / 'org.example.room.service'
    if change in ('unit edited', 'force unchanged'):
        api.write_text('[Service]\nUser=reviewed\n')  # --force replaces it; the review saw this content
    assert serve.install(linux, 'owner', tmp_path, False, False, change in ('unit edited', 'force unchanged'), 'org.example.room') == 0
    root, = [line.strip() for line in capsys.readouterr().out.splitlines() if line.strip().startswith('sudo ')]
    stage, = (tmp_path / '.local/state/postern').glob('install-*')
    if change == 'unit appeared':  # for example a package or another admin wrote it between review and sudo
        (systemd.UNIT_DIR / 'org.example.room.watchdog.service').write_text('[Service]\nUser=someone-else\n')
    elif change == 'unit edited':
        api.write_text('[Service]\nUser=edited-after-review\n')
    elif change == 'drop-in appeared':
        (systemd.UNIT_DIR / 'org.example.room.watchdog.service.d').mkdir()
    elif change == 'staged unit edited':  # the service account owns the stage; the API runs as that account
        staged = stage / 'org.example.room.service'
        staged.write_text(staged.read_text().replace('User=owner', 'User=root'))
    elif change == 'install.sh edited':
        (stage / 'install.sh').write_text('#!/bin/sh\ninstall evil /etc/systemd/system/evil.service\n')
    elif change.endswith('is /dev/zero'):  # an endless source: root's bounded read stops it, the digest refuses it
        target = stage / ('install.sh' if change.startswith('install.sh') else 'org.example.room.service')
        target.unlink()
        target.symlink_to('/dev/zero')
    binary, log = tmp_path / 'bin', tmp_path / 'root-commands.log'
    binary.mkdir()
    for name in ('install', 'systemctl'):
        (binary / name).write_text(f'#!/bin/sh\necho "{name} $*" >> {shlex.quote(str(log))}\n')
        (binary / name).chmod(0o755)
    command = shlex.split(root)
    assert command[0] == 'sudo'
    ran = subprocess.run(command[1:], env={'PATH': f'{binary}:{ROOT_PATH}'}, capture_output=True, text=True, timeout=30)
    commands = log.read_text().splitlines() if log.exists() else []
    if change in ('none', 'force unchanged'):
        assert ran.returncode == 0, ran.stderr
        assert [line.split()[0] for line in commands] == ['install'] * 3 + ['systemctl'] * 3
        assert commands[3] == 'systemctl --system daemon-reload' and commands[-1].startswith('systemctl --system restart')
    else:
        assert ran.returncode != 0 and commands == [], f'exit {ran.returncode} after {change}; ran {commands}'


