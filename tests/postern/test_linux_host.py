@pytest.mark.parametrize('uid,enabled', [('1000', False), ('0', False), ('1000', True)])
def test_linux_reboot_check_requires_enabled_units_and_refuses_root(tmp_path, uid, enabled):
    # Only fake executables enter PATH; the script cannot reach real systemctl, HTTP or a config.
    binary = tmp_path / 'bin'
    binary.mkdir()
    systemctl_body = ('case "$*" in *is-enabled*) echo enabled;; esac' if enabled else
                      'case "$*" in *is-enabled*watchdog*) echo disabled; exit 1;; *is-enabled*) echo enabled;; esac')
    for name, body in {'systemctl': systemctl_body,
                       'curl': 'exit 0', 'uptime': 'echo synthetic-boot', 'python': 'echo 12345', 'id': f'echo {uid}'}.items():
        path = binary / name
        path.write_text('#!/bin/sh\n' + body + '\n')
        path.chmod(0o755)
    script = serve.ROOT / 'ops/postern/reboot-check-linux.sh'
    checked = subprocess.run(['/bin/sh', str(script), str(tmp_path / 'config.json'), 'org.example.room', str(binary / 'python')],
                             env={'PATH': str(binary)}, capture_output=True, text=True)
    if uid == '0':  # as root it would run the release tree's Python, which the service account can change
        assert checked.returncode == 1 and checked.stdout == '' and 'not as root' in checked.stderr
    elif enabled:
        assert checked.returncode == 0 and checked.stdout.count('enabled and active') == 3
        assert 'local API answered' in checked.stdout
    else:
        assert checked.returncode == 1 and 'watchdog.service must be enabled and active' in checked.stdout


